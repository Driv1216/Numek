def test_evidence_deletion_replays_at_its_K_and_affected_analyses_refuse_as_in_v2(shared, tmp_path):
    from confidenceguard.migration import migrate_workspace
    root, entry = fixture('cg3_deletion', tmp_path)
    analysis = legacy_result(root, entry['analysis_ids']['analysis'])
    report = migrate_workspace(root)
    checks = report['validation']['checks']
    assert report['validation']['passed'], {k: v for k, v in checks.items() if not v['passed']}
    assert checks['deletion_tombstones']['tombstoned'] > 0
    # The earlier analysis never read the deleted batch and re-executes equal; the later one refuses, as on v2.
    assert checks['cg3_reexecution']['analyses'] == 1 and checks['cg3_reexecution']['refused_after_deletion_as_in_v2'] == 1
    migrated = ReliabilityWorkspace(root)
    assert migrated.status()['catalog_sequence'] == entry['catalog_sequence']
    assert migrated.evidence_tracking()['continuity'] == 'incomplete'
    assert migrated.open(entry['analysis_ids']['analysis']).to_private_dict() == analysis
    with pytest.raises(EvaluationError) as caught:
        migrated.analyze(_cg3().longitudinal(migrated))
    assert caught.value.code == 'historical_evidence_unavailable'


def test_local_workspace_migration_completes_only_with_its_post_cutover_backup(monkeypatch, tmp_path, cluster):
    from confidenceguard.migration import migrate_workspace, migration_status
    from numek_platform.local import LocalCluster
    monkeypatch.delenv('NUMEK_PLATFORM_DSN', raising=False)
    root, entry = fixture('cg3', tmp_path)
    tracked = legacy_result(root, entry['analysis_ids']['tracked'])
    restored_root = Path(tmp_path).resolve() / 'restored'
    try:
        report = migrate_workspace(root)
        assert report['complete'] is False and report['incomplete_reason'] == 'post_cutover_backup_required'
        report = migrate_workspace(root, backup_destination=Path(tmp_path).resolve() / 'post-cutover-backup')
        assert report['complete'] is True and report['backup'] and migration_status(root)['complete'] is True
        restored = ReliabilityWorkspace.restore(Path(tmp_path).resolve() / 'post-cutover-backup', restored_root)
        assert restored.open(entry['analysis_ids']['tracked']).to_private_dict() == tracked
    finally:
        for path in (root, restored_root):
            if (path / 'platform').exists():
                LocalCluster(path / 'platform').stop()


def test_cg4_cg5_cg6_workspace_migrates_with_governance_artifacts_and_reexecution(shared, tmp_path):
    """Typed features, retained investigations and confirmations, evidence uses with study budgets,
    policy families and CG6 binary artifacts migrate; a CG4 investigation re-executes equal."""
    from confidenceguard.execution.artifact_bytes import verify_artifact
    from confidenceguard.history_storage import LegacyCatalog
    from confidenceguard.investigation_contracts import InvestigationSpec
    from confidenceguard.migration import ORDER_DEPENDENT, differences, migrate_workspace
    from tests.backend_support import evidence_uses
    root, entry = fixture('multi', tmp_path)
    ids = entry['analysis_ids']
    expected = {aid: legacy_result(root, aid) for aid in ids.values()}
    legacy_uses = sorted((u['id'], u['kind']) for u in (f['payload'] for f in LegacyCatalog(root).iter_facts('evidence_use')))
    report = migrate_workspace(root)
    checks = report['validation']['checks']
    assert report['validation']['passed'], {k: v for k, v in checks.items() if not v['passed']}
    assert checks['retained_assessments']['assessments'] >= len(ids) and checks['objects_identity_and_bytes']['verified_bytes'] > 0

    migrated = ReliabilityWorkspace(root)
    assert migrated.status()['catalog_sequence'] == entry['catalog_sequence'] and migrated.status()['facts'] == entry['facts']
    assert sorted((u['id'], u['kind']) for u in evidence_uses(migrated)) == legacy_uses        # the ledger, use for use
    for aid, value in expected.items():
        assert migrated.open(aid).to_private_dict() == value
    reopened = migrated.open(ids['executed'])                                                 # CG6 bytes at v2 paths
    output = reopened.private['output_artifact']
    verify_artifact({**output, 'path': reopened.retained_path(output['path'])}, (migrated.path,))
    spec = entry['frozen_spec']
    spec['history']['workspace_path'] = str(root)                                             # the fixture moved
    rerun = migrated.investigate(InvestigationSpec.from_dict(spec))                            # CG4 re-executes equal
    # The fixture was extracted elsewhere: the input fingerprint binds the spec, which names the workspace path.
    moved = (re.compile(r'workspace_path$'), re.compile(r'(^|/)path$'), re.compile(r'^/investigation/fingerprint$'))
    assert differences(expected[ids['discovery']], rerun.to_private_dict(), ignore=ORDER_DEPENDENT + moved) == []


def test_deleting_and_purging_a_migrated_workspace_removes_the_frozen_v2_copies(shared, tmp_path):
    from confidenceguard.migration import migrate_workspace
    root, entry = fixture('cg3', tmp_path)
    migrate_workspace(root)
    ws = ReliabilityWorkspace(root)
    fact = next(ws.catalog.iter_facts('prediction'))
    frozen_copy = root / 'objects' / (fact['object_id'] + '.jsonl')
    assert frozen_copy.exists()
    ws.delete(ws.deletion_preview(object_ids=[fact['object_id']]))
    assert not frozen_copy.exists()                                   # deleted evidence leaves no v2 copy
    ReliabilityWorkspace(root).delete(ReliabilityWorkspace(root).deletion_preview(purge=True))
    assert not (root / 'catalog.sqlite3').exists() and not list((root / 'objects').iterdir())

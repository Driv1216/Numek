"""Catalog v2 -> platform migration (S3c): replay, validation, cutover, interruption and abandon.

The sources are frozen catalog v2 workspaces generated by the last runtime with the v2 writer
(``validation/cg7/generate_catalog_v2_fixtures.py``; identity in ``tests/fixtures/catalog_v2/manifest.json``).
Results on the migrated platform workspace are compared with the frozen source read through
the read-only legacy view.
"""
import hashlib
import json
import re
import sqlite3
import tarfile
from pathlib import Path

import pytest

from confidenceguard import EvaluationError, ReliabilityWorkspace

FIXTURES = Path(__file__).resolve().parents[1] / 'fixtures' / 'catalog_v2'
MANIFEST = json.loads((FIXTURES / 'manifest.json').read_text())


def fixture(name, tmp_path):
    """Extract a verified copy of a frozen v2 fixture workspace; returns (root, manifest entry)."""
    entry = MANIFEST['fixtures'][name]
    archive = FIXTURES / entry['archive']
    assert hashlib.sha256(archive.read_bytes()).hexdigest() == entry['sha256']
    target = Path(tmp_path).resolve() / name
    target.mkdir(mode=0o700)
    with tarfile.open(archive) as tar:
        tar.extractall(target, filter='tar')
    return target / 'workspace', entry


def legacy_result(root, aid):
    from confidenceguard.history_storage import LegacyCatalog
    return LegacyCatalog(root).assessment(aid).to_private_dict()


def _shift(path, offset):
    rows = path.read_text().splitlines()
    path.write_text('\n'.join([rows[0]] + [','.join([str(offset + int(r.split(',')[0]))] + r.split(',')[1:])
                                           for r in rows[1:]]) + '\n')


def _cg3():
    from test_cg3_on_platform import _cg3_helpers
    return _cg3_helpers()


@pytest.fixture
def shared(platform, monkeypatch):
    monkeypatch.setenv('NUMEK_PLATFORM_DSN', platform.db.dsn)
    return platform


def test_unmigrated_v2_workspaces_are_refused_with_the_migration_path(tmp_path):
    root, _entry = fixture('cg3', tmp_path)
    with pytest.raises(EvaluationError) as caught:
        ReliabilityWorkspace(root)
    assert caught.value.code == 'migration_required'


def test_cg3_workspace_migrates_with_preserved_identity_and_validated_equivalence(shared, tmp_path):
    from confidenceguard.history_storage import LegacyCatalog
    from confidenceguard.migration import migrate_workspace
    from confidenceguard.platform_catalog import PlatformCatalog
    root, entry = fixture('cg3', tmp_path)
    ids = entry['analysis_ids']
    instance = LegacyCatalog(root).instance_id
    expected = {name: legacy_result(root, ids[name]) for name in ('first', 'restated', 'tracked')}
    report = migrate_workspace(root)
    checks = report['validation']['checks']
    assert report['state'] == 'cutover_committed' and report['validation']['passed'], {k: v for k, v in checks.items() if not v['passed']}
    assert checks['cg3_reexecution']['analyses'] == 3 and checks['evidence_governance']['uses'] >= 1
    assert report['complete'] is False and report['incomplete_reason'] == 'post_cutover_backup_required_on_shared_installation'

    migrated = ReliabilityWorkspace(root)
    assert isinstance(migrated.catalog, PlatformCatalog) and migrated.instance_id == instance
    assert migrated.status()['catalog_sequence'] == entry['catalog_sequence'] and migrated.status()['facts'] == entry['facts']
    for name, value in expected.items():
        assert migrated.open(ids[name]).to_private_dict() == value
    with pytest.raises(EvaluationError):
        migrated.open(ids['doomed'])
    helpers = _cg3()
    # An idempotent request made under v2 answers identically on the platform.
    assert migrated.analyze(helpers.longitudinal(migrated), request_id='first').to_private_dict() == expected['first']
    # The migrated workspace keeps working: new evidence continues at K + 1.
    later = helpers.batch(Path(tmp_path).resolve(), 'later', count=12)
    _shift(Path(later['evaluation']['sources'][0]['path']), 300)
    assert migrated.ingest(later)['catalog_sequence'] == entry['catalog_sequence'] + 1
    from numek_platform.legacy import catalog_v2
    assert catalog_v2.user_version(root) == catalog_v2.FROZEN_VERSION                      # v2 stays frozen read-only
    assert json.loads((root / '.numek-migration.json').read_text())['state'] == 'cutover_committed'


def test_interrupted_migration_resumes_at_every_boundary_and_stays_inaccessible(shared, monkeypatch, tmp_path):
    from confidenceguard import migration
    from numek_platform.legacy import catalog_v2
    root, entry = fixture('cg3', tmp_path)
    head = entry['catalog_sequence']
    tracked = legacy_result(root, entry['analysis_ids']['tracked'])
    for boundary in ('planned', 'frozen', 'after_k:1', f'after_k:{head - 1}', 'copied', 'cutover'):
        def crash(name, boundary=boundary):
            if name == boundary:
                raise RuntimeError('synthetic crash at ' + boundary)
        monkeypatch.setattr(migration, 'fault', crash)
        with pytest.raises(RuntimeError, match=boundary):
            migration.migrate_workspace(root)
        if boundary != 'cutover':
            with pytest.raises(EvaluationError) as caught:                                 # nobody can use it meanwhile
                ReliabilityWorkspace(root)
            assert caught.value.code == 'catalog_unavailable'
        if boundary != 'planned':
            assert catalog_v2.user_version(root) == catalog_v2.FROZEN_VERSION
    monkeypatch.setattr(migration, 'fault', lambda name: None)
    report = migration.migrate_workspace(root)                                              # completes after cutover
    assert report['state'] == 'cutover_committed' and report['validation']['passed']
    migrated = ReliabilityWorkspace(root)
    assert migrated.status()['catalog_sequence'] == head
    assert migrated.open(entry['analysis_ids']['tracked']).to_private_dict() == tracked


def test_abandon_before_cutover_restores_catalog_v2(shared, monkeypatch, tmp_path):
    from confidenceguard import migration
    from numek_platform.legacy import catalog_v2
    root, entry = fixture('cg3', tmp_path)
    _body, inventory = catalog_v2.inventory(root)
    first = legacy_result(root, entry['analysis_ids']['first'])
    monkeypatch.setattr(migration, 'fault', lambda name: (_ for _ in ()).throw(RuntimeError(name)) if name == 'after_k:3' else None)
    with pytest.raises(RuntimeError):
        migration.migrate_workspace(root)
    assert migration.abandon_workspace(root)['state'] == 'abandoned'
    assert not (root / 'platform.json').exists() and not (root / '.numek-migration.json').exists()
    assert catalog_v2.user_version(root) == 2 and catalog_v2.inventory(root)[1] == inventory     # v2 exactly as before
    assert legacy_result(root, entry['analysis_ids']['first']) == first
    with shared.db.connect() as conn:                                                       # nothing left usable
        states = {r['state'] for r in conn.execute("SELECT state FROM catalogs WHERE name LIKE '%%:abandoned:%%'")}
    assert states == {'retired'}
    monkeypatch.setattr(migration, 'fault', lambda name: None)
    assert migration.migrate_workspace(root)['validation']['passed']                        # and it can migrate again


def test_source_changed_after_freeze_refuses_to_continue(shared, monkeypatch, tmp_path):
    from confidenceguard import migration
    root, _entry = fixture('cg3', tmp_path)
    monkeypatch.setattr(migration, 'fault', lambda name: (_ for _ in ()).throw(RuntimeError(name)) if name == 'frozen' else None)
    with pytest.raises(RuntimeError):
        migration.migrate_workspace(root)
    with sqlite3.connect(root / 'catalog.sqlite3') as db:                                  # someone edits the frozen source
        db.execute("UPDATE operations SET request_digest = 'tampered' WHERE sequence = 1")
    monkeypatch.setattr(migration, 'fault', lambda name: None)
    with pytest.raises(EvaluationError) as caught:
        migration.migrate_workspace(root)
    assert caught.value.code == 'migration_source_changed'



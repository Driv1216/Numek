// Captures real browser screenshots of every concept screen at fixed viewports.
// Usage: node scripts/capture-concepts.mjs [conceptId ...]   (dev server must be running)
import { chromium } from 'playwright';
import fs from 'node:fs';

const BASE = process.env.LAB_URL || 'http://127.0.0.1:5190';
const CHROME =
  process.env.CHROME_PATH ||
  `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`;
const ids = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const all = ['census', 'instrument', 'trace', 'cells', 'screening', 'inspect', 'continual', 'assurance', 'argument', 'signal', 'provenance', 'proof', 'engine', 'terrain', 'notebook'];
const list = ids.length ? ids : all;
const screens = ['landing', 'workspace', 'results'];
const sizes = [
  { tag: 'desktop', width: 1440, height: 900 },
  { tag: 'mobile', width: 390, height: 844 },
];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
fs.mkdirSync('public/screenshots', { recursive: true });

const browser = await chromium.launch({ executablePath: CHROME, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
for (const size of sizes) {
  const ctx = await browser.newContext({ viewport: { width: size.width, height: size.height }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  const fullCtx = await browser.newContext({ viewport: { width: size.width, height: size.height }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const full = await fullCtx.newPage();
  for (const id of list) {
    for (const s of screens) {
      await page.goto(`${BASE}/#/${id}/${s}`, { waitUntil: 'load', timeout: 60000 });
      await page.evaluate(() => document.fonts.ready);
      await sleep(2600);
      await page.screenshot({ path: `public/screenshots/${id}-${s}-${size.tag}.jpg`, type: 'jpeg', quality: 82 });
      if (s === 'landing' && size.tag === 'desktop' && process.env.SCROLL_SHOTS) {
        // Mid-page frames show scroll-driven sequences in their live state.
        for (const [n, vh] of [[1, 1.9], [2, 3.3]]) {
          await page.evaluate(() => window.scrollTo(0, 0));
          await sleep(300);
          for (let y = 0; y < vh * size.height; y += 300) {
            await page.mouse.move(700, 450);
            await page.mouse.wheel(0, 300);
            await sleep(70);
          }
          await sleep(1600);
          await page.screenshot({ path: `public/screenshots/${id}-landing-scroll${n}.jpg`, type: 'jpeg', quality: 82 });
        }
      }
      if (size.tag === 'desktop') {
        // Full-length captures use reduced motion so smooth scrolling and
        // scroll-driven reveals cannot leave the page offset or half-revealed.
        await full.goto(`${BASE}/#/${id}/${s}`, { waitUntil: 'load' });
        await full.evaluate(() => document.fonts.ready);
        const h = await full.evaluate(() => document.documentElement.scrollHeight);
        for (let y = 0; y < h; y += 700) {
          await full.evaluate((v) => window.scrollTo(0, v), y);
          await sleep(90);
        }
        await full.evaluate(() => window.scrollTo(0, 0));
        await sleep(1500);
        await full.screenshot({ path: `public/screenshots/${id}-${s}-full.jpg`, type: 'jpeg', quality: 74, fullPage: true });
      }
      console.log(id, s, size.tag);
    }
  }
  await ctx.close();
  await fullCtx.close();
}
await browser.close();

// A plain contact sheet of every capture, viewable at /screenshots/index.html.
const files = fs.readdirSync('public/screenshots').filter((f) => f.endsWith('.jpg')).sort();
const rows = all
  .map((id) => {
    const cells = screens
      .map((s) =>
        ['desktop', 'mobile', 'full']
          .map((t) => `${id}-${s}-${t}.jpg`)
          .filter((f) => files.includes(f))
          .map((f) => `<a href="${f}"><img src="${f}" alt="${f}" loading="lazy"><span>${f}</span></a>`)
          .join(''),
      )
      .join('');
    return `<h2>${id}</h2><div class="row">${cells}</div>`;
  })
  .join('\n');
fs.writeFileSync(
  'public/screenshots/index.html',
  `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Concept captures</title>
<style>body{font:14px system-ui;margin:32px;background:#f4f4f2;color:#1b1b1a}h2{margin:32px 0 10px}.row{display:flex;gap:10px;overflow-x:auto;align-items:flex-start}a{flex:none;text-decoration:none;color:#666;font-size:11px}img{display:block;height:300px;border:1px solid #ddd;background:#fff}</style>
<h1>Real browser captures</h1><p>Desktop 1440×900 viewport, mobile 390×844 viewport, and desktop full page. Generated by scripts/capture-concepts.mjs.</p>
${rows}`,
);

"""Deterministic fixtures for the J2 dossier: a planted positive corpus and adversarial ("hard") nulls.

Run: python validation/regression_dependency/fixtures.py   (writes fixtures/ and fixtures/manifest.json)
Every file is regenerated byte-identically from SEED.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).parent
SEED = 20261125
NOISES = ("none", "meas", "label1")


def noise_features(rng, n):
    return {"noise_num": rng.normal(size=n), "noise_cat": rng.choice([f"c{i:02d}" for i in range(12)], n),
            "noise_code": rng.integers(0, 10, n), "noise_skew": rng.lognormal(0, 1, n)}


def labels(k, prefix):
    width = len(str(k))
    return np.array([f"{prefix}{i:0{width}d}" for i in range(k)])


def apply_target_noise(rng, y, noise):
    y = np.asarray(y, dtype=float).copy()
    if noise == "meas":
        y = y + rng.normal(0, 1e-3 * (np.std(y) or 1), len(y))
    elif noise == "label1":
        idx = rng.choice(len(y), max(1, len(y) // 100), replace=False)
        donors = rng.choice(len(y), len(idx), replace=False)
        y[idx] = y[donors]
    return y


def lookup(rng, n, k, noise, *, sizes="uniform", numeric=False, missing=0.0):
    if sizes == "uniform":
        codes = rng.integers(0, k, n)
    else:  # zipf-like long tail
        p = 1 / np.arange(1, k + 1) ** 1.1
        codes = rng.choice(k, n, p=p / p.sum())
    prices = np.round(rng.uniform(5, 500, k), 2)
    while len(set(prices)) < k:
        prices = np.round(rng.uniform(5, 500, k), 2)
    y = apply_target_noise(rng, prices[codes], noise)
    feature = (codes + 1).astype(float) if numeric else labels(k, "p")[codes].astype(object)
    if missing:
        drop = rng.random(n) < missing
        feature = feature.astype(object); feature[drop] = None
        if numeric:
            feature = pd.array(feature, dtype="Float64")
    return feature, y


def binned(rng, n, noise, *, bins=5, style="str", edges=None):
    y = rng.gamma(2.0, 20.0, n)
    cut = np.quantile(y, np.linspace(0, 1, bins + 1)[1:-1]) if edges is None else np.asarray(edges)
    code = np.searchsorted(cut, y, side="right")
    k = int(code.max()) + 1
    if noise == "meas":
        y = y + rng.normal(0, 1e-3 * np.std(y), n)   # observed target noisy, bins from the clean value
    elif noise == "label1":
        idx = rng.choice(n, n // 100, replace=False)
        code = code.copy(); code[idx] = (code[idx] + rng.integers(1, k, len(idx))) % k
    feature = (code + 1) if style == "int" else labels(k, "band_")[code].astype(object)
    return feature, y


def monotone(rng, n, kind, noise):
    if kind == "log":
        x = rng.lognormal(3, 1, n); y = np.log(x)
    elif kind == "rank":
        x = np.round(rng.normal(50, 10, n), 1); y = pd.Series(x).rank().to_numpy()
    elif kind == "reciprocal":
        x = rng.uniform(1, 100, n); y = 1 / x
    elif kind == "cubic":
        x = rng.normal(0, 1, n); y = x ** 3
    elif kind == "step":
        x = rng.uniform(0, 10, n); y = np.floor(x)
    elif kind == "affine":
        x = rng.normal(0, 1, n); y = 3 * x + 2
    return x, apply_target_noise(rng, y, noise)


def positive_cases():
    """(name, builder, planted feature, expected family, noise, note)."""
    cases = []
    lookups = [("lookup_k5", dict(n=1000, k=5)), ("lookup_k12", dict(n=1000, k=12)), ("lookup_k40", dict(n=1000, k=40)),
               ("lookup_k40_n200", dict(n=200, k=40)), ("lookup_longtail_k60", dict(n=1000, k=60, sizes="zipf")),
               ("lookup_k12_missing10", dict(n=1000, k=12, missing=0.10)), ("code_lookup_k8", dict(n=1000, k=8, numeric=True))]
    for name, kw in lookups:
        for noise in NOISES:
            cases.append((f"{name}__{noise}", ("lookup", kw), "product" if not kw.get("numeric") else "product_code",
                          "categorical_determination", noise, ""))
    cases.append(("lookup_sparse_k80_n200__none", ("lookup", dict(n=200, k=80)), "product", "categorical_determination", "none",
                  "below_support_by_design"))
    for name, kw in [("binned_q5_str", dict(bins=5)), ("binned_q10_int", dict(bins=10, style="int")),
                     ("binned_custom_str", dict(edges=[10, 20, 35, 50, 75, 100]))]:
        for noise in NOISES:
            cases.append((f"{name}__{noise}", ("binned", kw), "band", "target_interval_coding", noise, ""))
    for kind in ("log", "rank", "reciprocal", "cubic", "step"):
        for noise in NOISES:
            cases.append((f"mono_{kind}__{noise}", ("monotone", dict(kind=kind)), "x", "monotone_mapping", noise, ""))
    cases.append(("control_affine__none", ("monotone", dict(kind="affine")), "x", "existing_affine_identity", "none",
                  "routed_to_existing_search"))
    return cases


def build_positive(name, spec, planted, noise, rng):
    kind, kw = spec
    kw = dict(kw)
    n = kw.pop("n", 1000)
    if kind == "lookup":
        feature, y = lookup(rng, n, noise=noise, **kw)
    elif kind == "binned":
        feature, y = binned(rng, n, noise, **kw)
    else:
        feature, y = monotone(rng, n, kw["kind"], noise)
    frame = pd.DataFrame(noise_features(rng, n))
    frame.insert(0, planted, feature)
    frame["target"] = y
    return frame


def hard_nulls(rng):
    """Targets independent of every feature, shaped to provoke chance determination."""
    out = {}

    def cats(n):
        p = 1 / np.arange(1, 31) ** 1.1
        return {"cat40": labels(40, "a")[rng.integers(0, 40, n)], "cat66": labels(66, "b")[rng.integers(0, 66, n)],
                "cat_zipf30": labels(30, "z")[rng.choice(30, n, p=p / p.sum())], "code10": rng.integers(0, 10, n),
                "row_id": labels(n, "r"), "account_key": labels(n // 2, "k")[rng.permutation(np.arange(n) // 2)],
                "noise_num": rng.normal(size=n)}

    n = 200
    out["skewed_discrete_n200"] = {**cats(n), "target": rng.choice(7, n, p=[.9, .03, .02, .02, .01, .01, .01])}
    n = 150
    out["poisson_n150"] = {**cats(n), "target": rng.poisson(1.0, n)}
    n = 100
    out["uniform5_n100"] = {"cat20_exact5": labels(20, "g")[rng.permutation(np.repeat(np.arange(20), 5))],
                            "cat10": labels(10, "h")[rng.integers(0, 10, n)], "code25": rng.integers(0, 25, n),
                            "target": rng.integers(0, 5, n)}
    n = 125
    out["continuous_cat25_exact5"] = {"cat25_exact5": labels(25, "g")[rng.permutation(np.repeat(np.arange(25), 5))],
                                      "code20": rng.integers(0, 20, n), "target": rng.normal(size=n)}
    n = 300
    out["near_constant_n300"] = {**cats(n), "target": np.r_[np.zeros(288), np.repeat([1, 2, 3, 4, 5, 6], 2)][rng.permutation(n)]}
    n = 60
    out["monotone_edge_n60"] = {"x20": np.repeat(np.arange(20), 3)[rng.permutation(n)].astype(float),
                                "x60": rng.normal(size=n), "target": rng.normal(size=n)}
    return {k: pd.DataFrame(v) for k, v in out.items()}


def main():
    manifest = {"seed": SEED, "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(), "positive": {}, "hard_null": {}}
    rng = np.random.default_rng(SEED)
    pos = ROOT / "fixtures/positive"; pos.mkdir(parents=True, exist_ok=True)
    for name, spec, planted, family, noise, note in positive_cases():
        frame = build_positive(name, spec, planted, noise, rng)
        path = pos / f"{name}.csv"; frame.to_csv(path, index=False)
        manifest["positive"][name] = {"file": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                      "target": "target", "planted_feature": planted, "family": family, "noise": noise,
                                      "note": note, "rows": len(frame), "features": len(frame.columns) - 1, "builder": spec[0], "params": spec[1]}
    hard = ROOT / "fixtures/hard_null"; hard.mkdir(parents=True, exist_ok=True)
    for name, frame in hard_nulls(np.random.default_rng(SEED + 1)).items():
        path = hard / f"{name}.csv"; frame.to_csv(path, index=False)
        manifest["hard_null"][name] = {"file": str(path.relative_to(ROOT)), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                       "target": "target", "rows": len(frame), "features": len(frame.columns) - 1}
    (ROOT / "fixtures/manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


if __name__ == "__main__":
    m = main()
    print(f"{len(m['positive'])} positive and {len(m['hard_null'])} hard-null fixtures written")

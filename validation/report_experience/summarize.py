"""Summarise a measured phase into readable tables.

Usage: PYTHONPATH=src:. .venv/bin/python -B -m validation.report_experience.summarize --phase before
Reads results/<phase>/summary.json and results/<phase>/<case>/metrics.json; writes results/<phase>/SUMMARY.md and
results/<phase>/rows_per_page.json (table rows on well-filled pages, by table class and orientation: spike f).
"""
import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent


def mib(value):
    return f'{value / 1024 ** 2:,.0f} MiB'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--phase', required=True)
    args = parser.parse_args()
    root = HERE / 'results' / args.phase
    summary = json.loads((root / 'summary.json').read_text())
    lines = [f'# Report Experience — {args.phase} measurements', '',
             'Generated by `validation/report_experience/measure.py`; one machine, not capacity guarantees.', '',
             '```', json.dumps(summary['environment'], indent=1), '```', '',
             '| Case | Variant | Mode | Findings | Pages (P/L) | HTML | HTML render (s) | PDF (s) | PDF peak RSS | Mean fill | Pages < 40% fill (excl. last) | Finding titles in PDF |',
             '|---|---|---|---|---|---|---|---|---|---|---|---|']
    rows_per_page = {}
    unavailable = []
    for name, case in summary['cases'].items():
        if 'unavailable' in case:
            unavailable.append((name, case['unavailable'].splitlines()[-1][:200]))
            continue
        metrics = json.loads((root / name / 'metrics.json').read_text())
        for variant, entry in case['variants'].items():
            lines.append(f"| {name} | {variant} | {case['mode']} | {case['finding_count']} | {entry['pages']} "
                         f"({entry['portrait_pages']}/{entry['landscape_pages']}) | {entry['html_bytes']:,} B | "
                         f"{entry['html_render_s_median']} | {entry['pdf_total_s_median']} | {mib(entry['pdf_peak_rss_bytes_median'])} | "
                         f"{entry['fill']['mean']} | {', '.join(map(str, entry['fill']['pages_below_40pct_excluding_last'])) or '—'} | "
                         f"{entry['finding_titles_in_pdf']}/{entry['findings_titles']} |")
            for page in metrics['variants'][variant]['table_rows_per_page']:
                if page['fill'] is None or page['fill'] < 0.9 or len(page['rows']) != 1:
                    continue
                (table, count), = page['rows'].items()
                rows_per_page.setdefault(f"{table} ({page['orientation']})", []).append(count)
    if unavailable:
        lines += ['', '## Unavailable cases', ''] + [f'- **{n}**: {why}' for n, why in unavailable]
    lines += ['', '## Section page spans (canonical variant)', '']
    for name, case in summary['cases'].items():
        if 'unavailable' in case:
            continue
        entry = case['variants'].get('canonical') or next(iter(case['variants'].values()))
        spans = ', '.join(f"{title[:40]} p{s['first_page']}+{s['pages_touched']}" for title, s in entry['sections'].items())
        lines.append(f'- **{name}**: {spans}')
    lines += ['', '## Analysis JSON identity', '', '| Case | Mode | Normalised SHA-256 | Re-run identical |', '|---|---|---|---|']
    for name, case in summary['cases'].items():
        if 'unavailable' in case:
            continue
        a = case['analysis_json']
        lines.append(f"| {name} | {case['mode']} | `{a['normalized_sha256'][:16]}…` | {a.get('rerun_normalized_identical', 'not re-run')} |")
    table = {k: {'pages': len(v), 'median': statistics.median(v), 'min': min(v), 'max': max(v)} for k, v in sorted(rows_per_page.items())}
    (root / 'rows_per_page.json').write_text(json.dumps(table, indent=1) + '\n')
    lines += ['', '## Table rows per well-filled page (spike f)', '',
              'Pages at least 90% filled and holding rows of a single table class.', '',
              '| Table class (orientation) | Pages | Median rows | Min | Max |', '|---|---|---|---|---|']
    lines += [f"| {k} | {v['pages']} | {v['median']} | {v['min']} | {v['max']} |" for k, v in table.items()]
    (root / 'SUMMARY.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
